export type ColormapName = 'viridis' | 'plasma' | 'cividis' | 'inferno';

function decode(hex: string): Uint8Array {
  const out = new Uint8Array(768);
  for (let i = 0; i < 768; i++) {
    out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

const TABLES: Record<ColormapName, Uint8Array> = {
  viridis: decode(VIRIDIS_HEX),
  plasma: decode(PLASMA_HEX),
  cividis: decode(CIVIDIS_HEX),
  inferno: decode(INFERNO_HEX),
};

/** Raw 256×RGB bytes, e.g. for WebGL texture upload. */
export function lut(name: ColormapName): Uint8Array {
  return TABLES[name];
}

/** Sample a colormap at t ∈ [0,1] with linear interpolation. Returns [r,g,b] 0–255. */
export function sample(name: ColormapName, t: number): [number, number, number] {
  const table = TABLES[name];
  const x = Math.min(1, Math.max(0, t)) * 255;
  const i = Math.floor(x);
  const j = Math.min(255, i + 1);
  const f = x - i;
  return [
    table[i * 3] * (1 - f) + table[j * 3] * f,
    table[i * 3 + 1] * (1 - f) + table[j * 3 + 1] * f,
    table[i * 3 + 2] * (1 - f) + table[j * 3 + 2] * f,
  ];
}

/** CSS color string for a colormap sample. */
export function css(name: ColormapName, t: number): string {
  const [r, g, b] = sample(name, t);
  return `rgb(${Math.round(r)}, ${Math.round(g)}, ${Math.round(b)})`;
}

/**
 * n distinct series colours drawn from a ramp, avoiding the light tail that
 * gets lost on white backgrounds (t kept in [0, 0.85]).
 */
export function seriesColors(name: ColormapName, n: number): string[] {
  if (n === 1) return [css(name, 0.45)];
  const out: string[] = [];
  for (let i = 0; i < n; i++) out.push(css(name, (0.85 * i) / (n - 1)));
  return out;
}

/** Write a field (values in [0,1]) into an RGBA ImageData buffer. */
export function fieldToRGBA(
  name: ColormapName,
  field: Float32Array | Float64Array,
  rgba: Uint8ClampedArray
): void {
  const table = TABLES[name];
  for (let i = 0; i < field.length; i++) {
    const t = field[i];
    const idx = (t <= 0 ? 0 : t >= 1 ? 255 : (t * 255) | 0) * 3;
    rgba[i * 4] = table[idx];
    rgba[i * 4 + 1] = table[idx + 1];
    rgba[i * 4 + 2] = table[idx + 2];
    rgba[i * 4 + 3] = 255;
  }
}
